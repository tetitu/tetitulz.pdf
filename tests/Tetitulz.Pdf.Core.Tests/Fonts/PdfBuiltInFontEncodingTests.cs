using System.Collections.Generic;
using Tetitulz.Pdf.Core.Fonts;
using Tetitulz.Pdf.Core.Objects;

namespace Tetitulz.Pdf.Core.Tests.Fonts;

/// <summary>
/// Unit tests for PDF spec §9.6.6.4: Symbol and ZapfDingbats always use their
/// built-in encodings regardless of /Encoding or /ToUnicode entries.
/// </summary>
public sealed class PdfBuiltInFontEncodingTests
{
    // ZapfDingbats code 0x33 → U+2713 (✓) in the built-in encoding.
    // WinAnsiEncoding / a common producer's incorrect ToUnicode maps it to '3' instead.

    [Fact]
    public void ZapfDingbats_WithBadToUnicodeCmap_DecodesCheckmarkNotThree()
    {
        // Arrange: font dict with BaseFont /ZapfDingbats and a ToUnicode CMap that
        // incorrectly maps code 0x33 → "3" (as generated by common producers).
        var fontDict = new PdfDictionary();
        fontDict[PdfName.Subtype]  = new PdfName("Type1");
        fontDict[PdfName.BaseFont] = new PdfName("ZapfDingbats");

        var badToUnicode = new Dictionary<int, string> { { 0x33, "3" } };

        // null document is fine: ZapfDingbats path in the constructor never calls
        // document.ResolveObject (encoding is set directly from the BaseFont name).
        var font = new PdfType1Font(fontDict, null, badToUnicode);

        // Act
        string result = font.Decode(new byte[] { 0x33 });

        // Assert: must be ✓ (U+2713), not '3'
        Assert.Equal("✓", result);
    }

    [Fact]
    public void ZaDb_WithBadToUnicodeCmap_DecodesCheckmarkNotThree()
    {
        // ZaDb is the a common viewer alias for ZapfDingbats used in widget AP streams.
        var fontDict = new PdfDictionary();
        fontDict[PdfName.Subtype]  = new PdfName("Type1");
        fontDict[PdfName.BaseFont] = new PdfName("ZaDb");

        var badToUnicode = new Dictionary<int, string> { { 0x33, "3" } };

        var font = new PdfType1Font(fontDict, null, badToUnicode);

        string result = font.Decode(new byte[] { 0x33 });

        Assert.Equal("✓", result);
    }

    [Fact]
    public void Symbol_WithBadToUnicodeCmap_UsesBuiltInEncoding()
    {
        // Symbol code 0x61 → U+03B1 (α) in the built-in Symbol encoding.
        var fontDict = new PdfDictionary();
        fontDict[PdfName.Subtype]  = new PdfName("Type1");
        fontDict[PdfName.BaseFont] = new PdfName("Symbol");

        var badToUnicode = new Dictionary<int, string> { { 0x61, "a" } }; // incorrect: WinAnsi 'a'

        var font = new PdfType1Font(fontDict, null, badToUnicode);

        string result = font.Decode(new byte[] { 0x61 });

        // Must not be 'a' — should be the Symbol encoding's value for 0x61.
        Assert.NotEqual("a", result);
    }

    [Fact]
    public void ZapfDingbatsTrueType_WithBadToUnicodeCmap_DecodesCheckmarkNotThree()
    {
        // Same fix also applies to PdfTrueTypeFont (some generators use TrueType subtype
        // for ZapfDingbats widget fonts).
        var fontDict = new PdfDictionary();
        fontDict[PdfName.Subtype]  = new PdfName("TrueType");
        fontDict[PdfName.BaseFont] = new PdfName("ZapfDingbats");

        var badToUnicode = new Dictionary<int, string> { { 0x33, "3" } };

        var font = new PdfTrueTypeFont(fontDict, null, badToUnicode);

        string result = font.Decode(new byte[] { 0x33 });

        Assert.Equal("✓", result);
    }

    [Fact]
    public void RegularFont_ToUnicodeTakesPriority()
    {
        // For non-built-in fonts, ToUnicode CMap MUST still win over /Encoding.
        // This verifies the bypass is limited to Symbol/ZapfDingbats/ZaDb.
        var fontDict = new PdfDictionary();
        fontDict[PdfName.Subtype]  = new PdfName("Type1");
        fontDict[PdfName.BaseFont] = new PdfName("Helvetica");
        fontDict[PdfName.Encoding] = new PdfName("WinAnsiEncoding");

        // ToUnicode maps 0x41 → "A" (correct), let's override to verify it's used.
        var toUnicode = new Dictionary<int, string> { { 0x41, "X" } };

        // Need null document for Helvetica path too — but it calls document.ResolveObject
        // for the encoding name. Since Encoding is a PdfName (not an indirect ref),
        // we need a document. Use the string-indexer overload to avoid that code path
        // by omitting /Encoding so the default WinAnsiEncoding is picked, then pass
        // a ToUnicode map for a known code.
        var fontDictNoEnc = new PdfDictionary();
        fontDictNoEnc[PdfName.Subtype]  = new PdfName("Type1");
        fontDictNoEnc[PdfName.BaseFont] = new PdfName("Helvetica");
        // No /Encoding → defaults to WinAnsiEncoding (no document needed)

        var font = new PdfType1Font(fontDictNoEnc, null, toUnicode);

        string result = font.Decode(new byte[] { 0x41 });

        // ToUnicode maps 0x41 → "X", so result should be "X", not "A"
        Assert.Equal("X", result);
    }
}
