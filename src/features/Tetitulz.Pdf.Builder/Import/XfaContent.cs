using System;
using System.Collections.Generic;
using System.IO;
using System.Linq;
using Tetitulz.Pdf.Builder.Model;
using Tetitulz.Pdf.Core;
using Tetitulz.Pdf.Core.Document;
using Tetitulz.Pdf.Core.Forms;
using Tetitulz.Pdf.Core.Objects;

namespace Tetitulz.Pdf.Builder.Import
{
    /// <summary>How <see cref="XfaContent.Read"/> presents what it found.</summary>
    public sealed class XfaContentOptions
    {
        /// <summary>Heading placed above the content; <c>null</c> writes none.</summary>
        public string? Title { get; set; }

        /// <summary>
        /// Whether a leaf the form left empty appears as a row with no value. Off by default: a
        /// datasets tree carries every field the template declared, filled or not, so a mostly-blank
        /// form would otherwise read as pages of empty rows.
        /// </summary>
        public bool IncludeEmptyValues { get; set; }
    }

    /// <summary>
    /// Reads a <b>dynamic</b> XFA form's content out of a PDF and builds a <see cref="Document"/>
    /// from it — which every Builder exporter then writes as PDF, DOCX, HTML or ODT.
    /// </summary>
    /// <remarks>
    /// <para><b>What this is for.</b> A dynamic XFA form has no pages until an XFA processor lays
    /// them out from the <c>template</c> packet, so a reader that is not one shows the producer's
    /// placeholder — "Please wait… if this message is not eventually replaced". The form's content
    /// is nonetheless entirely present in the <c>datasets</c> packet, which this library already
    /// reads. This turns that into something a person can read.</para>
    ///
    /// <para><b>What it is not, stated plainly because the distinction is the whole design.</b> It
    /// is the form's <i>content</i>, not the designer's layout: no captions, no boxes, no page
    /// geometry and no interactive fields. ISO 32000-2 Annex K makes that a conforming answer —
    /// "whether or not the pages generated by the processing of an XFA schema are materialized as
    /// PDF pages is implementation dependent", and "a PDF processor may choose to not implement this
    /// feature" — and XFA was deprecated in PDF 2.0.</para>
    ///
    /// <para><b>Nothing here reads the template packet, and that is deliberate.</b> The XFA template
    /// grammar is specified outside ISO 32000-2 (the XML Template Specification, XFA 3.3) and this
    /// repository does not hold that text, so a template reader would be a grammar written from
    /// recollection — which CLAUDE.md's stopping rule forbids, for the reason §2a records. The
    /// datasets packet needs no grammar: it is an XML tree of the form's own element names. The
    /// designed layout is <see cref="XfaLayout"/>'s, built on this assembly's absolute placement,
    /// flow, tables and pagination.</para>
    ///
    /// <para><b>Why it lives in Builder rather than in its own feature.</b> It produces a
    /// <see cref="Document"/>, which is Builder's own type; it needs only <c>Core</c>, which Builder
    /// already references; and it carries no third-party dependency and no weight. <c>DocxToPdf</c>
    /// is a separate assembly because it has both. Here a new package would buy nothing and cost a
    /// row in every register that counts them.</para>
    ///
    /// <para><b>Order is by path, not by document order.</b> The leaves arrive in a dictionary, and
    /// a dictionary's enumeration order is an implementation detail — a document whose sections
    /// shuffle between runs is worse than one in name order.</para>
    /// </remarks>
    public static class XfaContent
    {
        /// <summary>
        /// Why the last call produced no document, or <c>null</c> after one that produced content.
        /// </summary>
        /// <remarks>
        /// <c>[ThreadStatic]</c>, and cleared at the start of every call on every path — the rule
        /// every <c>Last*</c> slot in this repository follows.
        /// </remarks>
        public static string? LastError
        {
            get => _lastError;
            private set => _lastError = value;
        }

        [ThreadStatic]
        private static string? _lastError;

        /// <summary>
        /// <c>true</c> when <paramref name="pdf"/> carries an <c>/AcroForm /XFA</c> entry at all.
        /// </summary>
        /// <remarks>
        /// Says nothing about whether the form is static or dynamic — that distinction lives in the
        /// template packet, which this type does not read. A static form's content is reachable
        /// through its AcroForm as well; a dynamic one's is only here.
        /// </remarks>
        /// <param name="pdf">The PDF to inspect. Not disposed.</param>
        public static bool IsPresent(Stream pdf)
        {
            if (pdf == null) throw new ArgumentNullException(nameof(pdf));
            LastError = null;
            try
            {
                using var doc = PdfDocument.Open(pdf);
                return XfaPacket.IsPresent(doc.AcroForm?.Dictionary);
            }
            catch (PdfException ex)
            {
                LastError = ex.Message;
                return false;
            }
        }

        /// <summary>
        /// The form's content as a document, or <c>null</c> when there is none to read — see
        /// <see cref="LastError"/> for which of the reasons applied.
        /// </summary>
        /// <param name="pdf">The PDF to read. Not disposed.</param>
        /// <param name="options">Presentation policy; null uses the defaults.</param>
        public static Document? Read(Stream pdf, XfaContentOptions? options = null)
        {
            if (pdf == null) throw new ArgumentNullException(nameof(pdf));
            LastError = null;
            options ??= new XfaContentOptions();

            IReadOnlyDictionary<string, string>? values = ReadValues(pdf);
            if (values == null) return null;

            var rows = values
                .Where(v => options.IncludeEmptyValues || !string.IsNullOrEmpty(v.Value))
                .OrderBy(v => v.Key, StringComparer.Ordinal)
                .ToList();

            if (rows.Count == 0)
            {
                LastError = "the datasets packet carries no values";
                return null;
            }

            var builder = new DocumentBuilder();
            builder.AddSection(section =>
            {
                if (!string.IsNullOrEmpty(options.Title))
                    section.AddParagraph(p => p.AddText(options.Title!).Bold().FontSize(16));

                foreach (var group in rows.GroupBy(r => Group(r.Key), StringComparer.Ordinal))
                {
                    if (group.Key.Length > 0)
                        section.AddParagraph(p => p.AddText(group.Key).Bold().FontSize(12));

                    section.AddTable(table =>
                    {
                        foreach (var row in group)
                            table.AddRow(r => r.AddCell(FieldNames.Leaf(row.Key)).AddCell(row.Value));
                    });
                }
            });

            return builder.Build();
        }

        /// <summary>The datasets leaves by dotted path, or <c>null</c> with <see cref="LastError"/> set.</summary>
        private static IReadOnlyDictionary<string, string>? ReadValues(Stream pdf)
        {
            try
            {
                using var doc = PdfDocument.Open(pdf);
                PdfDictionary? acroForm = doc.AcroForm?.Dictionary;
                if (!XfaPacket.IsPresent(acroForm))
                {
                    LastError = "the document carries no /AcroForm /XFA entry";
                    return null;
                }

                XfaPacket? packet = XfaPacket.Read(acroForm, doc);
                PdfStream? datasets = packet?.GetPacketStream(XfaPacket.DatasetsPacket);
                if (datasets == null)
                {
                    // The same two causes PdfXfaFormFiller distinguishes, worded the same way: an
                    // unpackaged single-stream XDP, or a packaged entry carrying no datasets packet.
                    LastError = packet == null
                        ? "the /XFA entry did not resolve to any packet stream"
                        : packet.IsPackaged
                            ? "the /XFA array carries no 'datasets' packet"
                            : "the /XFA entry is a single XDP stream rather than named packets, so "
                              + "its datasets cannot be addressed without splitting the XDP";
                    return null;
                }

                byte[]? bytes = XfaPacket.BoundedBytes(datasets, out string refused);
                if (bytes == null)
                {
                    LastError = "the datasets packet could not be read: " + refused;
                    return null;
                }

                var values = XfaDatasets.ReadValues(bytes);
                if (values == null) LastError = "the datasets packet is not well-formed XML, or is past what a form holds";
                return values;
            }
            catch (PdfException ex)
            {
                LastError = ex.Message;
                return null;
            }
        }

        /// <summary>Everything above the leaf — the subform path the value sits in.</summary>
        private static string Group(string path)
        {
            int dot = path.LastIndexOf('.');
            return dot < 0 ? string.Empty : path.Substring(0, dot);
        }
    }
}
