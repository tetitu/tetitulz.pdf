    /// <summary>
    /// Builds a PDF MAC token per ISO/TS 32004 §6 — a CMS <c>AuthenticatedData</c> structure
    /// (RFC 5652) that authenticates an encrypted document's byte range, so tampering is detected
    /// independently of any digital signature.
    ///
    /// <para><b>Both placements are built here, and both are placed and checked.</b> §6.5.1's
    /// standalone token goes in an <c>AuthCode</c> dictionary and is written by
    /// <c>PdfMacTokenSeal</c>. §6.5.2's attached token — the same CMS with <c>signatureDigest</c>
    /// present — is built by <see cref="BuildAttachedToSigToken"/> and affixed to a signature's
    /// SignerInfo by <see cref="AttachToSignature"/>, which <c>PdfEncryptedSigner</c> drives through
    /// <c>SignaturePlan.CmsPostProcessor</c>. <see cref="Verify"/> reads either back.</para>
    ///
    /// <para><b>Building and checking are separate claims, and only the second one a document can
    /// falsify.</b> For a time this class could only build, so the digests it computed were asserted
    /// against nothing but themselves — a token that was wrong in the same way twice would have
    /// looked right. <see cref="Verify"/> is what makes a wrong key, a wrong digest or a swapped
    /// payload visible.</para>
    /// </summary>
    /// <remarks>
    /// <para><b>One of the files permitted to name BouncyCastle in this assembly</b> — a CMS
    /// <c>AuthenticatedData</c> structure has no BCL equivalent at all, on either target framework,
    /// which is the same category of justification the two original public-key-encryption files
    /// have (unlike <c>PdfGcmCipher.cs</c>, whose justification is netstandard2.0-specific, this one
    /// needs BouncyCastle on both legs). See <c>BouncyCastleConfinementTests</c>.</para>
    /// <para><b>Why this is hand-built rather than generated by
    /// <c>Org.BouncyCastle.Cms.CmsAuthenticatedDataGenerator</c>.</b> That generator's only
    /// password-recipient entry point, <c>AddPasswordRecipient(CmsPbeKey, string)</c>, is hard-wired
    /// to PBKDF2 (RFC 8018) — <c>CmsPbeKey</c>'s one extension point,
    /// <c>GetEncoded(string)</c>, is <c>internal</c>, so it cannot be subclassed from outside
    /// BouncyCastle to substitute the HKDF (RFC 5869) this TS mandates (§6.4). This builds the
    /// <c>PasswordRecipientInfo</c>/<c>AuthenticatedData</c>/<c>ContentInfo</c> structures directly
    /// from BouncyCastle's public ASN.1 model classes instead — the same approach
    /// <c>Tetitulz.Pdf.Signing.Cms.CmsDeferredSignatureBuilder</c> already takes for a CAdES shape
    /// BouncyCastle's own generators do not produce.</para>
    /// <para><b>Digest algorithm: SHA-256 only, for now.</b> ISO/TS 32004 Table 8 permits five
    /// others; SHA-256 is what §6.4's key-derivation function is fixed to regardless of which
    /// digest the token uses elsewhere, so using it throughout keeps one hash function in the whole
    /// construction rather than two. Extending to the other four is straightforward — swap the
    /// <see cref="Sha256Digest"/> instance and the digest AlgorithmIdentifier — but is not done here
    /// until a caller actually needs it.</para>
    /// <para><b>Verification boundary — stated plainly, not implied.</b> The three cryptographic
    /// primitives (HKDF-SHA256, AES-256 key wrap without padding, HMAC-SHA256) are each checked
    /// against their own independent RFC test vectors (5869, 3394, 4231) in
    /// <c>PdfMacTokenTests</c>. The composed CMS structure is checked by round-tripping through
    /// BouncyCastle's own <c>CmsAuthenticatedData</c> reader and by independently re-deriving the
    /// KEK/MAC key/MAC value in the test with a separately-written computation, so a bug shared
    /// between builder and test would have to be identical in both. What this does <b>not</b> have
    /// — because ISO/TS 32004's own Annex C gives only structural placeholders, no real bytes — is
    /// an official byte-exact "known good" PDF MAC token to compare against, the way
    /// <c>PdfGcmCipherTests</c> has for AES-GCM via NIST CAVP vectors.</para>
    /// </remarks>
    internal static class PdfMacToken
    {
        // ---- OIDs this TS mints (iso(1) standard(0) iso32004(32004) pdfmac(1) ...) ----

        /// <summary>id-ct-pdfMacIntegrityInfo (§6.2).</summary>
        internal const string IdCtPdfMacIntegrityInfo = "1.0.32004.1.0";

        /// <summary>id-kdf-pdfMacWrapKdf (§6.4).</summary>
        internal const string IdKdfPdfMacWrapKdf = "1.0.32004.1.1";

        /// <summary>
        /// id-attr-pdfMacData (§6.5.2) — the unsigned attribute a PDF MAC token is affixed to a
        /// signature under.
        /// </summary>
        /// <remarks>
        /// §6.5.2: "adding the MAC to an AuthCode dictionary is potentially problematic, because it
        /// affects signature coverage. In such cases, the PDF MAC token shall be affixed to the
        /// digital signature or document time stamp signature as an unsigned attribute." The
        /// attribute has exactly one value, and <c>PdfMacData ::= ContentInfo</c> — the same token
        /// §6.3 defines, not a different structure.
        /// </remarks>
        internal const string IdAttrPdfMacData = "1.0.32004.1.2";

        /// <summary>HKDF output length in bytes: a 256-bit KEK, matching the AES-256 wrap it feeds.</summary>
        internal const int KekLength = 32;

        /// <summary>MAC key length in bytes: 256 bits (ISO/TS 32004 Table 9, HMAC-SHA-256).</summary>
        internal const int MacKeyLength = 32;

        /// <summary>The literal 6-character ASCII/UTF-8 HKDF info parameter §6.4 mandates.</summary>
        private static readonly byte[] HkdfInfo = System.Text.Encoding.UTF8.GetBytes("PDFMAC");

        /// <summary>
        /// Builds a standalone PDF MAC token (§6.5.1): DER-encoded CMS <c>AuthenticatedData</c>,
        /// ready to hex-encode into an <c>AuthCode</c> dictionary's <c>MAC</c> entry.
        /// </summary>
        /// <param name="fileEncryptionKey">
        /// The document's file encryption key (the same key the security handler uses for
        /// document encryption) — the HKDF input key material per §6.4.
        /// </param>
        /// <param name="kdfSalt">The 32-byte value of the Encrypt dictionary's <c>/KDFSalt</c> entry.</param>
        /// <param name="dataDigest">
        /// SHA-256 digest of the bytes indicated by the <c>AuthCode</c> dictionary's
        /// <c>/ByteRange</c> entry (§6.6.2) — computed by the caller, since only the caller knows
        /// the final byte layout of the file being protected.
        /// </param>
        /// <param name="random">Source of randomness for the MAC key.</param>
        internal static byte[] BuildStandaloneToken(
            byte[] fileEncryptionKey, byte[] kdfSalt, byte[] dataDigest, SecureRandom random)
            => Build(fileEncryptionKey, kdfSalt, dataDigest, signatureDigest: null, random);

        /// <summary>
        /// Builds a PDF MAC token for a <b>signed</b> revision (§6.5.2): the same CMS structure with
        /// <c>signatureDigest</c> present, ready to affix to a signature's SignerInfo as the
        /// <see cref="IdAttrPdfMacData"/> unsigned attribute.
        /// </summary>
        /// <remarks>
        /// <para><b>Why a signed revision cannot use the standalone placement.</b> §6.5.2: putting
        /// the MAC in an <c>AuthCode</c> dictionary "affects signature coverage" — the token would
        /// cover the signature's own placeholders and stop verifying the moment the CMS is written
        /// into them, while the signature's <c>/ByteRange</c> covers the token. Affixing it as an
        /// <i>unsigned</i> attribute breaks that circularity: unsigned attributes are outside what
        /// the signature signs, and <c>/ByteRange</c> excludes the <c>/Contents</c> value the whole
        /// CMS lives in.</para>
        ///
        /// <para><b>Both digests are present, and that is deliberate.</b> §6.6.3 NOTE 2 records that
        /// <c>dataDigest</c> "ordinarily coincides with the value of the messageDigest attribute of
        /// the underlying SignerInfo" — it is carried anyway "so that the PDF MAC can be validated
        /// independently of the underlying signature", which is what lets the token attest to the
        /// document's integrity whatever the signature's validation status turns out to be.</para>
        /// </remarks>
        /// <param name="fileEncryptionKey">The document's file encryption key — §6.4's HKDF input.</param>
        /// <param name="kdfSalt">The 32-byte <c>/KDFSalt</c> from the Encrypt dictionary.</param>
        /// <param name="dataDigest">
        /// §6.6.3: the digest of the bytes the <b>signature dictionary's</b> <c>/ByteRange</c>
        /// indicates — not the <c>AuthCode</c> dictionary's, which a signed revision does not use
        /// for this.
        /// </param>
        /// <param name="signatureDigest">
        /// §6.6.3: the digest of <b>the value of the signature field in the SignerInfo</b> the token
        /// is attached to — the signature bytes themselves, not the signed attributes and not the
        /// document. The standard notes the computation is analogous to a signature timestamp's
        /// message imprint.
        /// </param>
        /// <param name="random">Source of randomness for the MAC key.</param>
        internal static byte[] BuildAttachedToSigToken(
            byte[] fileEncryptionKey, byte[] kdfSalt, byte[] dataDigest, byte[] signatureDigest,
            SecureRandom random)
        {
            if (signatureDigest == null || signatureDigest.Length != 32)
                throw new ArgumentException(
                    "signatureDigest must be a 32-byte SHA-256 digest of the SignerInfo's signature value.",
                    nameof(signatureDigest));

            return Build(fileEncryptionKey, kdfSalt, dataDigest, signatureDigest, random);
        }

        /// <summary>
        /// Affixes a §6.5.2 token to a finished CMS signature and returns the CMS to write —
        /// steps 5 to 7 of the AttachedToSig sequence, which only the signer's completion step can
        /// drive because only it holds the byte range and the CMS at the same moment.
        /// </summary>
        /// <remarks>
        /// <para><b>The signature value, not the signed attributes and not the document.</b> §6.6.3
        /// computes <c>signatureDigest</c> by "digesting the value of the signature field in the
        /// SignerInfo object on which the PDF MAC token is an unsigned attribute" — the raw
        /// signature bytes. NOTE 1 to that clause says the procedure is analogous to a signature
        /// timestamp's message imprint, and it is: the same bytes, the same reason.</para>
        ///
        /// <para><b>Adding it cannot invalidate the signature it is added to.</b> The attribute is
        /// <i>unsigned</i>, so it sits outside what the SignerInfo signs; and the whole CMS lives in
        /// the signature dictionary's <c>/Contents</c>, which <c>/ByteRange</c> excludes, so the CMS
        /// growing moves no byte that <paramref name="dataDigest"/> covered.</para>
        ///
        /// <para><b>The unsigned attribute is added by the signer's own helper</b>
        /// (<c>CmsSignatureGenerator.AddUnsignedAttribute</c>), which the RFC 3161 timestamp path
        /// also goes through. Attaching a DER value to every SignerInfo is one mechanic and two
        /// attributes; a second copy here could only agree with it or be a defect.</para>
        /// </remarks>
        /// <param name="cms">The finished CMS signature, DER-encoded.</param>
        /// <param name="dataDigest">§6.6.3's dataDigest — the digest of the bytes the signature's
        /// <c>/ByteRange</c> indicates, computed by the caller that read them.</param>
        /// <param name="fileEncryptionKey">The document's file encryption key (§6.4).</param>
        /// <param name="kdfSalt">The 32-byte <c>/KDFSalt</c>.</param>
        internal static byte[] AttachToSignature(
            byte[] cms, byte[] dataDigest, byte[] fileEncryptionKey, byte[] kdfSalt)
        {
            if (cms == null) throw new ArgumentNullException(nameof(cms));

            var signedData = new Org.BouncyCastle.Cms.CmsSignedData(ReadOneObject(cms));

            var signers = new System.Collections.Generic.List<Org.BouncyCastle.Cms.SignerInformation>(
                signedData.GetSignerInfos().GetSigners());
            if (signers.Count != 1)
                throw new Core.PdfException(
                    $"The signature contains {signers.Count} SignerInfo structures; ISO/TS 32004 §6.5.2 " +
                    "attaches the PDF MAC token to the one signature the revision was signed with, and " +
                    "there is no rule saying which of several it would be.");

            byte[] signatureDigest = Sha256(signers[0].GetSignature());

            byte[] token = BuildAttachedToSigToken(
                fileEncryptionKey, kdfSalt, dataDigest, signatureDigest, random: null);

            return Signing.Cms.CmsSignatureGenerator.EncodeForContents(
                Signing.Cms.CmsSignatureGenerator.AddUnsignedAttribute(
                    signedData, new DerObjectIdentifier(IdAttrPdfMacData), token));
        }

        /// <summary>
        /// The first encoded value in <paramref name="cms"/>, as a <c>ContentInfo</c>.
        /// </summary>
        /// <remarks>
        /// <b>Both entry points here take bytes that may come from a signature dictionary's
        /// <c>/Contents</c>, which is a FIXED-WIDTH reserve</b>: the CMS is followed by however many
        /// zero bytes were left over. Handing the whole string to a parser is refused as trailing
        /// garbage, and trimming the zeros is wrong twice over — an encoding may legitimately end in
        /// a zero byte, and an indefinite-length one always does, since its terminator is two of
        /// them. Reading exactly one object off the front is the only reading that is right in both
        /// cases, and it is here rather than at each call site so the two cannot disagree about it.
        /// </remarks>
        private static ContentInfo ReadOneObject(byte[] cms)
        {
            using (var asn1 = new Asn1InputStream(cms))
                return ContentInfo.GetInstance(asn1.ReadObject());
        }

        /// <summary>
        /// Extracts a §6.5.2 PDF MAC token from a signature's CMS, along with the signature value
        /// the token's <c>signatureDigest</c> is supposed to cover.
        /// </summary>
        /// <returns>False when the signature carries no such attribute.</returns>
        internal static bool TryExtractAttachedToken(
            byte[] cms, out byte[] token, out byte[] signatureValue)
        {
            token = null;
            signatureValue = null;
            if (cms == null) return false;

            Org.BouncyCastle.Cms.SignerInformation signer;
            try
            {
                var signedData = new Org.BouncyCastle.Cms.CmsSignedData(ReadOneObject(cms));
                var signers = new System.Collections.Generic.List<Org.BouncyCastle.Cms.SignerInformation>(
                    signedData.GetSignerInfos().GetSigners());
                if (signers.Count != 1) return false;
                signer = signers[0];
            }
            catch (Exception) { return false; }

            Org.BouncyCastle.Asn1.Cms.AttributeTable unsigned = signer.UnsignedAttributes;
            var oid = new DerObjectIdentifier(IdAttrPdfMacData);

            // §6.5.2: "The attribute shall have exactly one value." Two ways to break that, and
            // BOTH have to be refused — one attribute holding two values, and two attributes of the
            // same type holding one each. `AttributeTable`'s indexer answers with the FIRST match,
            // so checking only the value count accepts the second shape silently.
            //
            // This is not a theoretical distinction: the attribute is *unsigned*, so nothing in the
            // signature protects it and anyone may append one. A validator that picks the first of
            // two tokens is making the choice an attacker prepared for it.
            Asn1EncodableVector all = unsigned?.GetAll(oid);
            if (all == null || all.Count != 1) return false;

            var attribute = Attribute.GetInstance(all[0]);
            if (attribute.AttrValues.Count != 1) return false;

            token = attribute.AttrValues[0].ToAsn1Object().GetDerEncoded();
            signatureValue = signer.GetSignature();
            return true;
        }

        /// <summary>
        /// Verifies a PDF MAC token against the key that should have produced it and the digests it
        /// should carry — §6.3's structure, §6.6's digests — returning the first thing that does not
        /// hold, or null when everything does.
        /// </summary>
        /// <remarks>
        /// <para><b>The MAC covers the authenticated attributes, not the content</b>, so checking it
        /// alone proves nothing about the digests. RFC 5652 §9 binds the two through the
        /// <c>messageDigest</c> attribute, and ISO/TS 32004 §6.3.6.3 restates that requirement: the
        /// attribute holds a hash of the eContent <i>octet string value</i>. Verifying the MAC and
        /// then reading <c>dataDigest</c> out of the content <b>without</b> that check would accept
        /// a token whose content had been replaced wholesale — the attributes still authenticate,
        /// and they say nothing about what they are attached to.</para>
        ///
        /// <para><b>The attributes are re-encoded as a UNIVERSAL SET.</b> RFC 5652 §9.2 defines the
        /// MAC input as the DER encoding of the <c>AuthAttributes</c> value, not the bytes as
        /// transmitted — in the structure itself they are <c>[2] IMPLICIT</c>, which is a different
        /// tag over the same content. Building the input from the parsed attributes is what makes
        /// this the same computation <see cref="Build"/> performed, rather than a second reading of
        /// the same sentence.</para>
        ///
        /// <para><b>Comparisons are length-then-content in fixed time</b>, because a digest
        /// comparison that returns early leaks where the first difference is.</para>
        /// </remarks>
        /// <param name="token">The DER-encoded token.</param>
        /// <param name="fileEncryptionKey">The document's file encryption key (§6.4).</param>
        /// <param name="kdfSalt">The 32-byte <c>/KDFSalt</c>.</param>
        /// <param name="expectedDataDigest">
        /// The digest the caller computed over the bytes the relevant <c>/ByteRange</c> indicates.
        /// </param>
        /// <param name="expectedSignatureDigest">
        /// For §6.5.2, the digest of the SignerInfo's signature value; null for a standalone token,
        /// where §6.6.2 requires the field to be <b>absent</b> — and a token that carries one anyway
        /// is refused rather than ignored.
        /// </param>
        internal static string Verify(
            byte[] token, byte[] fileEncryptionKey, byte[] kdfSalt,
            byte[] expectedDataDigest, byte[] expectedSignatureDigest)
        {
            if (token == null) return "there is no PDF MAC token to verify.";
            if (kdfSalt == null || kdfSalt.Length != 32)
                return "the document's /KDFSalt is missing or is not 32 bytes, so no key can be derived (§6.4).";

            AuthenticatedData authenticated;
            try
            {
                var contentInfo = ContentInfo.GetInstance(Asn1Object.FromByteArray(token));
                if (contentInfo.ContentType?.Id != CmsObjectIdentifiers.AuthenticatedData.Id)
                    return $"the token's content type is {contentInfo.ContentType?.Id ?? "absent"}, not " +
                           $"id-ct-authData ({CmsObjectIdentifiers.AuthenticatedData.Id}) — §6.3.1.";

                authenticated = AuthenticatedData.GetInstance(contentInfo.Content);
            }
            catch (Exception ex)
            {
                return "the token is not a well-formed CMS AuthenticatedData structure: " + ex.Message;
            }

            if (authenticated.UnauthAttrs != null)
                return "the token carries unauthenticated attributes, which §6.3.7 forbids.";

            Asn1Set authAttrs = authenticated.AuthAttrs;
            if (authAttrs == null) return "the token has no authenticated attributes (§6.3.6.1).";

            byte[] macKey;
            try
            {
                byte[] wrapped = WrappedMacKey(authenticated);
                if (wrapped == null)
                    return "the token has no password recipient carrying a wrapped MAC key (§6.3.3).";

                macKey = UnwrapKey(DeriveKek(fileEncryptionKey, kdfSalt), wrapped);
            }
            catch (Exception ex)
            {
                // The document's own key did not open the token's MAC key. That is what a wrong
                // password looks like, and also what a token from another document looks like.
                return "the MAC key could not be unwrapped with this document's file encryption key: " + ex.Message;
            }

            byte[] expectedMac = ComputeHmacSha256(macKey, new DerSet(authAttrs.ToArray()).GetDerEncoded());
            if (!FixedTimeEquals(expectedMac, authenticated.Mac?.GetOctets()))
                return "the token's MAC does not match its authenticated attributes; the token has been altered.";

            // Only now is anything the token SAYS worth reading.
            byte[] eContent = (authenticated.EncapsulatedContentInfo?.Content as Asn1OctetString)?.GetOctets();
            if (eContent == null) return "the token encapsulates no content (§6.3.2).";

            string attributeProblem = CheckAuthenticatedAttributes(authAttrs, eContent);
            if (attributeProblem != null) return attributeProblem;

            byte[] dataDigest, signatureDigest;
            try
            {
                var info = Asn1Sequence.GetInstance(Asn1Object.FromByteArray(eContent));
                if (DerInteger.GetInstance(info[0]).IntValueExact != 0)
                    return "the PdfMacIntegrityInfo version is not 0, which §6.6.1 requires.";

                dataDigest = Asn1OctetString.GetInstance(info[1]).GetOctets();
                signatureDigest = info.Count > 2
                    ? Asn1OctetString.GetInstance(
                          Asn1TaggedObject.GetInstance(info[2]), false).GetOctets()
                    : null;
            }
            catch (Exception ex)
            {
                return "the token's PdfMacIntegrityInfo is not well formed (§6.2): " + ex.Message;
            }

            if (!FixedTimeEquals(dataDigest, expectedDataDigest))
                return "the token's dataDigest does not match the bytes the /ByteRange covers; " +
                       "the document has been altered since the token was made (§6.6).";

            // Presence itself is a requirement in both directions: §6.6.2 says the field shall be
            // absent in an unsigned revision, §6.6.3 that it shall be present in a signed one.
            if (expectedSignatureDigest == null)
                return signatureDigest == null
                    ? null
                    : "the token carries a signatureDigest, which §6.6.2 forbids in an unsigned revision.";

            if (signatureDigest == null)
                return "the token has no signatureDigest, which §6.6.3 requires in a signed revision.";

            return FixedTimeEquals(signatureDigest, expectedSignatureDigest)
                ? null
                : "the token's signatureDigest does not match the signature it is attached to (§6.6.3).";
        }

        /// <summary>§6.3.6.2 and §6.3.6.3, the two attributes that bind the content to the MAC.</summary>
        /// <remarks>
        /// <b>The two checks here are not the same kind of check, and a mutation sweep shows it.</b> Removing the <c>messageDigest</c> comparison is killed immediately — it
        /// is the only thing tying the token's payload to its MAC. Removing the <b>content-type</b>
        /// comparison survives every test, and honestly so: these are <i>authenticated</i>
        /// attributes, so altering one invalidates the MAC, which is checked before this method
        /// runs. The only party who can present a token whose content type is wrong and whose MAC is
        /// right is one holding the file encryption key — who can mint any token they please. So
        /// that line enforces RFC 5652 §11.1 conformance, not a security boundary, and there is no
        /// input this library can construct that reaches it. It stays because a non-conforming token
        /// should be named as such rather than read anyway; it is documented rather than deleted
        /// because an unexplained line that survives every mutation is what the next reader removes.
        /// </remarks>
        private static string CheckAuthenticatedAttributes(Asn1Set authAttrs, byte[] eContent)
        {
            var table = new Org.BouncyCastle.Asn1.Cms.AttributeTable(authAttrs);

            Attribute contentType = table[CmsAttributes.ContentType];
            if (contentType == null || contentType.AttrValues.Count != 1)
                return "the token does not carry exactly one content-type attribute (§6.3.6.2).";
            if (DerObjectIdentifier.GetInstance(contentType.AttrValues[0]).Id != IdCtPdfMacIntegrityInfo)
                return "the token's content-type attribute is not id-ct-pdfMacIntegrityInfo (§6.3.6.2).";

            Attribute messageDigest = table[CmsAttributes.MessageDigest];
            if (messageDigest == null || messageDigest.AttrValues.Count != 1)
                return "the token does not carry exactly one message-digest attribute (§6.3.6.3).";

            byte[] stated = Asn1OctetString.GetInstance(messageDigest.AttrValues[0]).GetOctets();
            return FixedTimeEquals(stated, Sha256(eContent))
                ? null
                : "the token's messageDigest attribute does not match its encapsulated content, so the " +
                  "authenticated attributes do not vouch for the digests the token carries (§6.3.6.3).";
        }

        /// <summary>The wrapped MAC key from the token's single password recipient (§6.3.3).</summary>
        private static byte[] WrappedMacKey(AuthenticatedData authenticated)
        {
            Asn1Set recipients = authenticated.RecipientInfos;
            if (recipients == null || recipients.Count != 1) return null;

            var recipient = RecipientInfo.GetInstance(recipients[0]);
            return recipient.Info is PasswordRecipientInfo password
                ? password.EncryptedKey?.GetOctets()
                : null;
        }

        /// <summary>
        /// Length-then-content comparison that does not return early on a mismatch.
        /// </summary>
        /// <remarks>
        /// Written here rather than taken from the BCL because
        /// <c>CryptographicOperations.FixedTimeEquals</c> does not exist on <c>netstandard2.0</c>,
        /// which is one of this project's two target frameworks.
        /// </remarks>
        private static bool FixedTimeEquals(byte[] a, byte[] b)
        {
            if (a == null || b == null || a.Length != b.Length) return false;

            int difference = 0;
            for (int i = 0; i < a.Length; i++) difference |= a[i] ^ b[i];
            return difference == 0;
        }

        /// <summary>
        /// The one construction behind both placements — they differ in a single optional field.
        /// </summary>
        /// <remarks>
        /// Written once rather than twice because everything except <c>signatureDigest</c> is
        /// identical: the same KEK derivation, the same wrapped MAC key, the same three
        /// authenticated attributes and the same re-tagging rule for the MAC input. Two copies could
        /// only agree or be a defect.
        /// </remarks>
        private static byte[] Build(
            byte[] fileEncryptionKey, byte[] kdfSalt, byte[] dataDigest, byte[] signatureDigest,
            SecureRandom random)
        {
            if (fileEncryptionKey == null) throw new ArgumentNullException(nameof(fileEncryptionKey));
            if (kdfSalt == null || kdfSalt.Length != 32)
                throw new ArgumentException("KDFSalt must be exactly 32 bytes.", nameof(kdfSalt));
            if (dataDigest == null || dataDigest.Length != 32)
                throw new ArgumentException("dataDigest must be a 32-byte SHA-256 digest.", nameof(dataDigest));
            random ??= new SecureRandom();

            var digestAlgId = new AlgorithmIdentifier(new DerObjectIdentifier(Core.Constants.PdfDigestOids.Sha256));

            // ---- §6.4: KEK = HKDF-SHA256(ikm = file key, salt = KDFSalt, info = "PDFMAC") ----
            byte[] kek = DeriveKek(fileEncryptionKey, kdfSalt);

            // ---- §6.3.3: a fresh random MAC key, wrapped under the KEK with AES-256 key wrap ----
            byte[] macKey = new byte[MacKeyLength];
            random.NextBytes(macKey);
            byte[] wrappedMacKey = WrapKey(kek, macKey);

            var keyDerivationAlgId = new AlgorithmIdentifier(new DerObjectIdentifier(IdKdfPdfMacWrapKdf));
            var keyEncryptionAlgId = new AlgorithmIdentifier(new DerObjectIdentifier(NistObjectIdentifiers.IdAes256Wrap.Id));
            var passwordRecipientInfo = new PasswordRecipientInfo(
                keyDerivationAlgId, keyEncryptionAlgId, new DerOctetString(wrappedMacKey));
            var recipientInfos = new DerSet(new RecipientInfo(passwordRecipientInfo));

            // ---- §6.2: PdfMacIntegrityInfo ::= SEQUENCE {
            //              version INTEGER,                                  -- shall be 0
            //              dataDigest OCTET STRING,
            //              signatureDigest [0] IMPLICIT OCTET STRING OPTIONAL }
            //
            // IMPLICIT, so the field is a [0] primitive octet string rather than a [0] wrapper
            // around one — DerTaggedObject(false, …) is that encoding. Absent in the standalone
            // case (§6.6.2) and required in the signed one (§6.6.3), which is the only structural
            // difference between the two placements.
            var integrityInfo = new Asn1EncodableVector
            {
                DerInteger.ValueOf(0),
                new DerOctetString(dataDigest),
            };

            if (signatureDigest != null)
                integrityInfo.Add(new DerTaggedObject(false, 0, new DerOctetString(signatureDigest)));

            byte[] pdfMacIntegrityInfo = new DerSequence(integrityInfo).GetDerEncoded();

            // ---- §6.3.2: encapContentInfo — eContentType = id-ct-pdfMacIntegrityInfo, eContent =
            // the DER bytes above, wrapped as an OCTET STRING. ContentInfo's own shape
            // (SEQUENCE { OID, [0] EXPLICIT content }) is structurally identical to
            // EncapsulatedContentInfo's, which is why AuthenticatedData's own constructor takes one. ----
            var encapContentInfo = new ContentInfo(
                new DerObjectIdentifier(IdCtPdfMacIntegrityInfo), new DerOctetString(pdfMacIntegrityInfo));

            // ---- §6.3.6.3: messageDigest = Hash(digestAlgorithm, eContent OCTET STRING VALUE) —
            // the raw bytes handed to DerOctetString above, not its tag/length octets (RFC
            // 5652:2009 §9.2/11.2). ----
            byte[] messageDigest = Sha256(pdfMacIntegrityInfo);

            // ---- §6.3.6: the three required authenticated attributes ----
            var contentTypeAttr = new Attribute(
                CmsAttributes.ContentType, new DerSet(new DerObjectIdentifier(IdCtPdfMacIntegrityInfo)));
            var messageDigestAttr = new Attribute(
                CmsAttributes.MessageDigest, new DerSet(new DerOctetString(messageDigest)));
            var macAlgId = new AlgorithmIdentifier(new DerObjectIdentifier(PkcsObjectIdentifiers.IdHmacWithSha256.Id));
            var algProtectionAttr = new Attribute(
                CmsAttributes.CmsAlgorithmProtect,
                new DerSet(new CmsAlgorithmProtection(digestAlgId, CmsAlgorithmProtection.Mac, macAlgId)));

            // A DerSet sorts its elements into DER order itself, so construction order here does
            // not have to match encoded order.
            var authAttrs = new DerSet(contentTypeAttr, messageDigestAttr, algProtectionAttr);

            // ---- §6.3.7: unauthAttrs absent. §5.4/9.2's re-tagging rule: the MAC is computed over
            // authAttrs encoded as an ordinary (UNIVERSAL) SET — the SAME object is then handed to
            // AuthenticatedData below, which re-tags it [2] IMPLICIT in the outer structure's own
            // encoding. One object, two encoding contexts — not two copies that could disagree. ----
            byte[] authAttrsForMac = authAttrs.GetDerEncoded();
            byte[] mac = ComputeHmacSha256(macKey, authAttrsForMac);

            var authenticatedData = new AuthenticatedData(
                originatorInfo: null,
                recipientInfos: recipientInfos,
                macAlgorithm: macAlgId,
                digestAlgorithm: digestAlgId,
                encapsulatedContent: encapContentInfo,
                authAttrs: authAttrs,
                mac: new DerOctetString(mac),
                unauthAttrs: null);

            // ---- §6.3.1: the PDF MAC token itself is a CMS ContentInfo of type id-ct-authData. ----
            var tokenContentInfo = new ContentInfo(
                new DerObjectIdentifier(CmsObjectIdentifiers.AuthenticatedData.Id), authenticatedData);

            return tokenContentInfo.GetDerEncoded();
        }

        /// <summary>§6.4: HKDF-SHA256(ikm, salt, info="PDFMAC") → a <see cref="KekLength"/>-byte KEK.</summary>
        internal static byte[] DeriveKek(byte[] fileEncryptionKey, byte[] kdfSalt)
        {
            var hkdf = new HkdfBytesGenerator(new Sha256Digest());
            hkdf.Init(new HkdfParameters(fileEncryptionKey, kdfSalt, HkdfInfo));
            byte[] kek = new byte[KekLength];
            hkdf.GenerateBytes(kek, 0, KekLength);
            return kek;
        }

        /// <summary>RFC 3394 AES key wrap without padding, per ISO/TS 32004 Table 7.</summary>
        internal static byte[] WrapKey(byte[] kek, byte[] keyToWrap)
        {
            var wrapper = new AesWrapEngine();
            wrapper.Init(true, new KeyParameter(kek));
            return wrapper.Wrap(keyToWrap, 0, keyToWrap.Length);
        }

        /// <summary>RFC 3394 AES key unwrap without padding — the inverse of <see cref="WrapKey"/>.</summary>
        internal static byte[] UnwrapKey(byte[] kek, byte[] wrappedKey)
        {
            var wrapper = new AesWrapEngine();
            wrapper.Init(false, new KeyParameter(kek));
            return wrapper.Unwrap(wrappedKey, 0, wrappedKey.Length);
        }

        /// <summary>RFC 2104/4231 HMAC-SHA256.</summary>
        internal static byte[] ComputeHmacSha256(byte[] key, byte[] data)
        {
            var hmac = new HMac(new Sha256Digest());
            hmac.Init(new KeyParameter(key));
            hmac.BlockUpdate(data, 0, data.Length);
            byte[] output = new byte[hmac.GetMacSize()];
            hmac.DoFinal(output, 0);
            return output;
        }

        internal static byte[] Sha256(byte[] data)
        {
            var digest = new Sha256Digest();
            digest.BlockUpdate(data, 0, data.Length);
            byte[] output = new byte[digest.GetDigestSize()];
            digest.DoFinal(output, 0);
            return output;
        }
    }
