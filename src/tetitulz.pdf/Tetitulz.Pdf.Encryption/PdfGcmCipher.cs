using System;
#if NETSTANDARD2_0
using Org.BouncyCastle.Crypto;
using Org.BouncyCastle.Crypto.Engines;
using Org.BouncyCastle.Crypto.Modes;
using Org.BouncyCastle.Crypto.Parameters;
#else
using System.Security.Cryptography;
#endif

namespace Tetitulz.Pdf.Encryption
{
    /// <summary>
    /// AES-GCM per ISO/TS 32003 (the <c>/CFM /AESV4</c> crypt filter, ISO 32000-2 / PDF 2.0): a
    /// 12-byte IV, the ciphertext, then a 16-byte authentication tag — and no additional
    /// authenticated data, which §5.2 requires to be nil.
    /// </summary>
    /// <remarks>
    /// <para><b>One of the files permitted to name BouncyCastle in this assembly</b> — extending
    /// the two the public-key envelope path already uses (<c>PdfPublicKeyEncryptor</c>,
    /// <c>PdfPublicKeyDecryptor</c>), for a reason specific to this cipher rather than a relaxation
    /// of the rule: .NET's own <c>System.Security.Cryptography.AesGcm</c> is net10.0-only — it is
    /// not part of the <c>netstandard2.0</c> API surface at all — so that leg has no BCL route to
    /// GCM. BouncyCastle is already this project's mandatory dependency (for the public-key path),
    /// so routing netstandard2.0 through its <c>GcmBlockCipher</c> adds no new package, only a
    /// documented, narrow reason for a third file to reach it. net10.0 still uses the native class,
    /// matching every other cipher in this codebase's stated preference for BCL over BouncyCastle
    /// wherever the BCL actually offers it.</para>
    /// <para><b>Verified against NIST CAVP, not only against itself.</b> A hand implementation and
    /// its own round trip agreeing proves nothing — encrypting with a bug and decrypting with the
    /// same bug still round-trips. <c>PdfGcmCipherTests</c> checks fixed ciphertext/tag bytes from
    /// the NIST GCM Encrypt test vectors (AES-256, 96-bit IV, empty AAD, 128-bit tag) instead.</para>
    /// </remarks>
    internal static class PdfGcmCipher
    {
        /// <summary>IV length ISO/TS 32003 §5.2 mandates: 12 bytes, generated by the security handler.</summary>
        internal const int IvLength = 12;

        /// <summary>Authentication tag length ISO/TS 32003 §5.2 mandates: 16 bytes.</summary>
        internal const int TagLength = 16;

        /// <summary>
        /// Encrypts <paramref name="plaintext"/> under AES-256-GCM with nil AAD, returning the
        /// ciphertext (same length as the plaintext) and the 16-byte authentication tag separately
        /// — framing them as <c>IV || ciphertext || tag</c> is the caller's job, since that byte
        /// layout is a PDF-object concern, not a cipher one.
        /// </summary>
        internal static void Encrypt(byte[] key, byte[] iv, byte[] plaintext, byte[] ciphertext, byte[] tag)
        {
#if NETSTANDARD2_0
            var cipher = new GcmBlockCipher(new AesEngine());
            cipher.Init(true, new AeadParameters(new KeyParameter(key), TagLength * 8, iv));
            byte[] output = new byte[cipher.GetOutputSize(plaintext.Length)];
            int len = cipher.ProcessBytes(plaintext, 0, plaintext.Length, output, 0);
            len += cipher.DoFinal(output, len);
            // BouncyCastle appends the tag after the ciphertext in one buffer; split it back apart
            // so both target frameworks hand the caller the same two-piece shape.
            Buffer.BlockCopy(output, 0, ciphertext, 0, plaintext.Length);
            Buffer.BlockCopy(output, plaintext.Length, tag, 0, TagLength);
#else
            using var gcm = new AesGcm(key, TagLength);
            gcm.Encrypt(iv, plaintext, ciphertext, tag);
#endif
        }

        /// <summary>
        /// Decrypts and authenticates <paramref name="ciphertext"/>/<paramref name="tag"/> under
        /// AES-256-GCM with nil AAD. Returns <c>false</c> — never throws, never returns partial
        /// plaintext — when the tag does not verify, which per ISO/TS 32003 means the ciphertext
        /// was tampered with or the key is wrong; the two are indistinguishable and must be, since
        /// telling them apart would leak which guess came closer.
        /// </summary>
        internal static bool TryDecrypt(byte[] key, byte[] iv, byte[] ciphertext, byte[] tag, out byte[] plaintext)
        {
#if NETSTANDARD2_0
            try
            {
                var cipher = new GcmBlockCipher(new AesEngine());
                cipher.Init(false, new AeadParameters(new KeyParameter(key), TagLength * 8, iv));
                byte[] input = new byte[ciphertext.Length + TagLength];
                Buffer.BlockCopy(ciphertext, 0, input, 0, ciphertext.Length);
                Buffer.BlockCopy(tag, 0, input, ciphertext.Length, TagLength);

                byte[] output = new byte[cipher.GetOutputSize(input.Length)];
                int len = cipher.ProcessBytes(input, 0, input.Length, output, 0);
                len += cipher.DoFinal(output, len);

                plaintext = new byte[len];
                Buffer.BlockCopy(output, 0, plaintext, 0, len);
                return true;
            }
            catch (InvalidCipherTextException)
            {
                plaintext = null;
                return false;
            }
#else
            var output = new byte[ciphertext.Length];
            using var gcm = new AesGcm(key, TagLength);
            try
            {
                gcm.Decrypt(iv, ciphertext, tag, output);
                plaintext = output;
                return true;
            }
            catch (CryptographicException)
            {
                plaintext = null;
                return false;
            }
#endif
        }
    }
}
