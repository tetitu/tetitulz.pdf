        /// <summary>MEL_E[k], the MEL decoder's exponent for state k (Table 2).</summary>
        internal static readonly int[] MelExponent = { 0, 0, 0, 1, 1, 1, 2, 2, 2, 3, 3, 4, 5 };

        private static readonly ushort[] Lookup0 = BuildLookup(Table0);
        private static readonly ushort[] Lookup1 = BuildLookup(Table1);

        /// <summary>A looked-up entry carries this bit; an empty slot is 0.</summary>
        internal const int Present = 0x8000;

        /// <summary>
        /// The lookup for the first row of quads (<paramref name="initialRow"/>) or the rest: slot
        /// <c>context · 256 + ((1 &lt;&lt; length) | bits)</c> holds, for a codeword, <see cref="Present"/> |
        /// ρ | u<sup>off</sup> &lt;&lt; 4 | ϵ<sup>k</sup> &lt;&lt; 5 | ϵ<sup>1</sup> &lt;&lt; 9; 0 where no codeword ends.
        /// </summary>
        internal static ushort[] Lookup(bool initialRow) => initialRow ? Lookup0 : Lookup1;

        private static readonly int[] Peek0 = BuildPeek(Lookup0);
        private static readonly int[] Peek1 = BuildPeek(Lookup1);

        /// <summary>
        /// The same codes indexed by the next <see cref="MaxCodewordLength"/> bits: slot <c>context · 128 + bits</c>
        /// holds the entry of the one codeword those bits begin with — every context's code is complete and
        /// prefix-free (<c>JpxHtCodeTablesTests</c>), so exactly one does — with its length in bits 16 and up.
        /// What the decoder reads a codeword by in one step, where <see cref="Lookup"/> reads it a bit at a time.
        /// </summary>
        internal static int[] Peek(bool initialRow) => initialRow ? Peek0 : Peek1;

        private static int[] BuildPeek(ushort[] lookup)
        {
            var peek = new int[8 * 128];
            for (int context = 0; context < 8; context++)
                for (int bits = 0; bits < 128; bits++)
                    for (int length = 1; length <= MaxCodewordLength; length++)
                    {
                        int entry = lookup[context * 256 + ((1 << length) | (bits & ((1 << length) - 1)))];
                        if (entry == 0) continue;
                        peek[context * 128 + bits] = entry | (length << 16);
                        break;
                    }
            return peek;
        }

        /// <summary>The lookup of <paramref name="table"/>: each entry at its context and codeword.</summary>
        internal static ushort[] BuildLookup(byte[] table)
        {
            var lookup = new ushort[8 * 256];
            for (int i = 0; i < table.Length; i += FieldsPerEntry)
            {
                int c = table[i], rho = table[i + 1], uoff = table[i + 2], ek = table[i + 3], e1 = table[i + 4];
                int w = table[i + 5], length = table[i + 6];
                lookup[c * 256 + ((1 << length) | w)] = (ushort)(Present | rho | (uoff << 4) | (ek << 5) | (e1 << 9));
            }
            return lookup;
        }
